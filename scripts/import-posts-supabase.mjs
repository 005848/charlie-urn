async function importPosts() {
  console.log('开始导入示例文章...');

  for (const post of posts) {
    const { data, error } = await supabase
      .from('blog_posts')
      .upsert({
        slug: post.slug,
        title: post.title,
        description: post.description,
        content: post.content,
        category: post.category,
        tags: post.tags,
        status: post.status,
        pub_date: post.pub_date,
      }, { onConflict: 'slug' })
      .select()
      .single();

    if (error) {
      console.error(`导入 ${post.slug} 失败:`, error.message);
    } else {
      console.log(`✓ ${post.title}`);
    }
  }

  console.log('导入完成！');
}

importPosts();
